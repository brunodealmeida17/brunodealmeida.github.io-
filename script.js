let currentLang = localStorage.getItem('portfolio-lang') || 'pt';

const navLinks = document.querySelectorAll('.nav-link');
const sections = document.querySelectorAll('.section');
const targetButtons = document.querySelectorAll('[data-section-target]');
const counters = document.querySelectorAll('[data-counter]');
const languageButtons = document.querySelectorAll('.lang-button');
let countersStarted = false;
const cursorGlow = document.getElementById('cursorGlow');

const languageSuffix = {
  en: 'En',
  it: 'It'
};

function localize(item, key) {
  const suffix = languageSuffix[currentLang];
  if (suffix && item[`${key}${suffix}`]) {
    return item[`${key}${suffix}`];
  }
  return item[key];
}

function translate(key) {
  return translations[currentLang][key] || translations.pt[key] || '';
}

function applyLanguage(lang = currentLang) {
  currentLang = lang;
  localStorage.setItem('portfolio-lang', currentLang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const translation = translations[currentLang][el.dataset.i18n];
    if (translation) el.textContent = translation;
  });

  languageButtons.forEach(button => button.classList.toggle('active', button.dataset.lang === currentLang));

  renderTimeline();
  renderSkills();
  renderProjects();

  const chatBox = document.getElementById('chatBox');
  if (chatBox) {
    chatBox.innerHTML = `<p class="assistant-message">${translate('assistantInitial')}</p>`;
  }
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

function showSection(sectionId) {
  sections.forEach(section => section.classList.toggle('active-section', section.id === sectionId));
  navLinks.forEach(link => link.classList.toggle('active', link.dataset.section === sectionId));
  revealVisibleCards();

  if (sectionId === 'home' && !countersStarted) {
    animateCounters();
  }
}

navLinks.forEach(link => {
  link.addEventListener('click', () => showSection(link.dataset.section));
});

targetButtons.forEach(button => {
  button.addEventListener('click', () => showSection(button.dataset.sectionTarget));
});

function animateCounters() {
  countersStarted = true;
  counters.forEach(counter => {
    const target = Number(counter.dataset.counter);
    let current = 0;
    const increment = Math.max(1, Math.ceil(target / 40));
    const interval = setInterval(() => {
      current += increment;
      if (current >= target) {
        counter.textContent = `${target}+`;
        clearInterval(interval);
      } else {
        counter.textContent = current;
      }
    }, 30);
  });
}

function renderTimeline() {
  const timelineList = document.getElementById('timelineList');
  timelineList.innerHTML = experiences.map((item, index) => `
    <button class="timeline-item ${index === 0 ? 'active' : ''}" data-index="${index}" type="button">
      <span class="timeline-year">${item.year}</span>
      <h3>${localize(item, 'company')}</h3>
      <p>${localize(item, 'role')}</p>
    </button>
  `).join('');

  timelineList.querySelectorAll('.timeline-item').forEach(button => {
    button.addEventListener('click', () => {
      timelineList.querySelectorAll('.timeline-item').forEach(item => item.classList.remove('active'));
      button.classList.add('active');
      renderExperience(Number(button.dataset.index));
    });
  });

  renderExperience(0);
}

function renderExperience(index) {
  const item = experiences[index];
  const panel = document.getElementById('experiencePanel');
  const highlights = localize(item, 'highlights');

  panel.innerHTML = `
    <p class="eyebrow">${localize(item, 'period')}</p>
    <h3>${localize(item, 'company')}</h3>
    <p><strong>${localize(item, 'role')}</strong> • ${localize(item, 'location')}</p>
    <ul>${highlights.map(highlight => `<li>${highlight}</li>`).join('')}</ul>
  `;
}

function renderSkills() {
  const skillButtons = document.getElementById('skillButtons');
  skillButtons.innerHTML = skills.map((skill, index) => `
    <button class="${index === 0 ? 'active' : ''}" data-index="${index}" type="button">${localize(skill, 'name')}</button>
  `).join('');

  skillButtons.querySelectorAll('button').forEach(button => {
    button.addEventListener('click', () => {
      skillButtons.querySelectorAll('button').forEach(item => item.classList.remove('active'));
      button.classList.add('active');
      renderSkillDetail(Number(button.dataset.index));
    });
  });

  renderSkillDetail(0);
}

function renderSkillDetail(index) {
  const skill = skills[index];
  const detail = document.getElementById('skillDetail');
  const description = localize(skill, 'description');
  const topics = localize(skill, 'topics');

  detail.innerHTML = `
    <p class="eyebrow">${translate('skillLevelPrefix')} ${skill.level}%</p>
    <h3>${localize(skill, 'name')}</h3>
    <div class="progress" aria-hidden="true"><div class="progress-bar"></div></div>
    <p>${description}</p>
    <ul>${topics.map(topic => `<li>${topic}</li>`).join('')}</ul>
  `;

  requestAnimationFrame(() => {
    detail.querySelector('.progress-bar').style.width = `${skill.level}%`;
  });
}

function renderProjects() {
  const projectGrid = document.getElementById('projectGrid');
  projectGrid.innerHTML = projects.map((project, index) => `
    <article class="project-card" data-index="${index}" tabindex="0" role="button" aria-label="${translate('projectModalLabel')} ${localize(project, 'title')}">
      <h3>${localize(project, 'title')}</h3>
      <p>${localize(project, 'summary')}</p>
      <div class="project-tags">${project.tags.map(tag => `<span class="tag">${tag}</span>`).join('')}</div>
    </article>
  `).join('');

  projectGrid.querySelectorAll('.project-card').forEach(card => {
    card.addEventListener('click', () => openProjectModal(Number(card.dataset.index)));
    card.addEventListener('keydown', event => {
      if (event.key === 'Enter') openProjectModal(Number(card.dataset.index));
    });
    attachTilt(card);
  });

  revealVisibleCards();
}

function openProjectModal(index) {
  const project = projects[index];
  document.getElementById('modalBody').innerHTML = `
    <p class="eyebrow">${translate('projectModalLabel')}</p>
    <h2>${localize(project, 'title')}</h2>
    <p>${localize(project, 'details')}</p>
    <div class="project-tags">${project.tags.map(tag => `<span class="tag">${tag}</span>`).join('')}</div>
    <div style="display:flex;flex-wrap:wrap;gap:12px;margin-top:20px;">
      ${project.demo ? `<a href="${project.demo}" target="_blank" rel="noopener noreferrer" style="display:inline-block;padding:10px 18px;background:linear-gradient(135deg,var(--primary),var(--primary-2));color:#fff;border-radius:12px;font-weight:700;text-decoration:none;">Ver demo ao vivo →</a>` : ''}
      ${project.link ? `<a href="${project.link}" target="_blank" rel="noopener noreferrer" style="display:inline-block;padding:10px 18px;border:1px solid var(--border);background:var(--surface-2);color:var(--text);border-radius:12px;font-weight:700;text-decoration:none;">Ver no GitHub →</a>` : ''}
    </div>
  `;
  document.getElementById('projectModal').classList.add('open');
  document.getElementById('projectModal').setAttribute('aria-hidden', 'false');
}

function closeProjectModal() {
  document.getElementById('projectModal').classList.remove('open');
  document.getElementById('projectModal').setAttribute('aria-hidden', 'true');
}

document.getElementById('modalClose').addEventListener('click', closeProjectModal);
document.getElementById('projectModal').addEventListener('click', event => {
  if (event.target.id === 'projectModal') closeProjectModal();
});

document.addEventListener('keydown', event => {
  if (event.key === 'Escape') closeProjectModal();
});

document.querySelectorAll('[data-question]').forEach(button => {
  button.addEventListener('click', () => {
    const answer = answers[currentLang][button.dataset.question];
    document.getElementById('chatBox').innerHTML = `<p class="assistant-message">${answer}</p>`;
  });
});

document.getElementById('themeToggle').addEventListener('click', () => {
  document.body.classList.toggle('light');
  localStorage.setItem('portfolio-theme', document.body.classList.contains('light') ? 'light' : 'dark');
});

function attachTilt(card) {
  card.addEventListener('pointermove', event => {
    const rect = card.getBoundingClientRect();
    const x = ((event.clientX - rect.left) / rect.width - .5) * 6;
    const y = ((event.clientY - rect.top) / rect.height - .5) * -6;
    card.style.transform = `perspective(900px) rotateX(${y}deg) rotateY(${x}deg) translateY(-2px)`;
  });

  card.addEventListener('pointerleave', () => {
    card.style.transform = '';
  });
}

function revealVisibleCards() {
  document.querySelectorAll('.active-section, .active-section .project-card, .active-section .text-card, .active-section .experience-panel, .active-section .skill-detail, .active-section .assistant-card, .active-section .contact-card').forEach((element, index) => {
    element.classList.remove('reveal-in');
    window.setTimeout(() => element.classList.add('reveal-in'), index * 45);
  });
}

if (cursorGlow && window.matchMedia('(pointer: fine)').matches) {
  window.addEventListener('pointermove', event => {
    cursorGlow.style.left = `${event.clientX}px`;
    cursorGlow.style.top = `${event.clientY}px`;
    cursorGlow.style.opacity = '1';
  });
}

if (localStorage.getItem('portfolio-theme') === 'light') {
  document.body.classList.add('light');
}

applyLanguage(currentLang);
animateCounters();
revealVisibleCards();
